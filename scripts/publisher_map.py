def publisher_from_doi(doi: str | None) -> tuple[str, str]:
    if not doi or not doi.lower().startswith("10."):
        return ("Other/unknown", "Other/unknown")
    pre = doi.lower().split("/")[0]
    return DOI_PREFIX.get(pre, ("Other/unknown", "Other/unknown"))
